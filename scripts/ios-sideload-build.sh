#!/usr/bin/env bash
# Builds the release app for a real iPhone as an .ipa to install with AltStore or SideStore and a free Apple ID
# (macOS with Xcode). No Apple account is needed here: the sideloading app signs the .ipa with the user's Apple ID
# when it installs it. The app and its widget are ad-hoc signed with their entitlements so that the sideloading
# app can carry the app group (shared with the widget) over to its own signature.
# Result: build/LekhaWise.ipa
set -euo pipefail
cd "$(dirname "$0")/.."
export CI=1
OUT=build/sideload
rm -rf "$OUT" build/LekhaWise.ipa
mkdir -p "$OUT"
xcodebuild -version

npx expo prebuild --platform ios --clean

WORKSPACE=$(ls -d ios/*.xcworkspace | head -1)
SCHEME=$(basename "$WORKSPACE" .xcworkspace)
started=$SECONDS
if ! xcodebuild -workspace "$WORKSPACE" -scheme "$SCHEME" -configuration Release -sdk iphoneos \
  -destination 'generic/platform=iOS' -derivedDataPath build/derived-device \
  COMPILER_INDEX_STORE_ENABLE=NO CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY= \
  build > "$OUT/xcodebuild.log" 2>&1; then
  grep -E 'error:|BUILD FAILED|The following build commands failed' -A4 "$OUT/xcodebuild.log" | head -150
  tail -40 "$OUT/xcodebuild.log"
  exit 1
fi
echo "Built in $((SECONDS - started)) s"

APP="$OUT/Payload/$SCHEME.app"
mkdir -p "$OUT/Payload"
cp -R "build/derived-device/Build/Products/Release-iphoneos/$SCHEME.app" "$APP"

# Entitlements of each target (app and widget), as generated by prebuild, keyed by product name.
xcodebuild -project "ios/$SCHEME.xcodeproj" -alltargets -configuration Release -showBuildSettings -json \
  2> /dev/null > "$OUT/build-settings.json"
node -e '
  const targets = JSON.parse(require("fs").readFileSync(process.argv[1], "utf8"));
  for (const { buildSettings: s } of targets) {
    if (s.CODE_SIGN_ENTITLEMENTS) console.log(`${s.FULL_PRODUCT_NAME}\t${s.SRCROOT}/${s.CODE_SIGN_ENTITLEMENTS}`);
  }' "$OUT/build-settings.json" > "$OUT/entitlements.tsv"
cat "$OUT/entitlements.tsv"

# Free Apple IDs cannot use push notifications, and values left as Xcode variables cannot be signed as they are.
clean_entitlements() {
  plutil -convert json -o - "$1" | node -e '
    const e = JSON.parse(require("fs").readFileSync(0, "utf8"));
    delete e["aps-environment"];
    for (const [k, v] of Object.entries(e)) if (JSON.stringify(v).includes("$(")) delete e[k];
    process.stdout.write(JSON.stringify(e));' > "$2.json"
  plutil -convert xml1 -o "$2" "$2.json"
  rm "$2.json"
}

sign() { # bundle, product name
  local source
  source=$(awk -F'\t' -v p="$2" '$1 == p { print $2 }' "$OUT/entitlements.tsv")
  if [ -n "$source" ]; then
    clean_entitlements "$source" "$OUT/$2.entitlements"
    codesign --force --sign - --entitlements "$OUT/$2.entitlements" "$1"
  else
    codesign --force --sign - "$1"
  fi
}

# Inside out: frameworks, then extensions (the widget), then the app.
find "$APP" -depth -name '*.framework' -print0 | while IFS= read -r -d '' f; do codesign --force --sign - "$f"; done
for appex in "$APP"/PlugIns/*.appex; do
  if [ -e "$appex" ]; then sign "$appex" "$(basename "$appex")"; fi
done
sign "$APP" "$SCHEME.app"

ls "$APP/PlugIns" || echo "No app extensions (widget missing)"
for bundle in "$APP" "$APP"/PlugIns/*.appex; do
  if [ -e "$bundle" ]; then echo "== $(basename "$bundle")"; codesign -d --entitlements - "$bundle" 2>&1; fi
done | tee "$OUT/signed-entitlements.txt"

(cd "$OUT" && zip -qry ../LekhaWise.ipa Payload)
ls -lh build/LekhaWise.ipa
